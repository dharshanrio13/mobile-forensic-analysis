def build_synthetic_evidence_zip(target_dir: Path) -> Path:
    """
    Write a small, clearly synthetic evidence ZIP into `target_dir`.

    The JSON shapes here were taken from the existing parsers in
    app/parsers/ - field names and value types match what those parsers
    actually accept. The archive also contains one unsupported file, so
    the extraction service's skip behaviour is exercised too.
    """
    archive_path = target_dir / "synthetic_evidence.zip"

    device = {
        "device_id": "SYNTHETIC-DEVICE-0001",
        "model": "Simulated Handset X",
        "os_version": "SimOS 1.0",
        "owner_reference": "SYNTHETIC-SUBJECT-A",
    }
    app_activity = [
        {"timestamp": TS_APP, "app": "SimChat", "action": "OPEN"},
        {"timestamp": TS_SYSTEM, "app": "SimChat", "action": "CLOSE"},
    ]
    calls = [
        {
            "timestamp": TS_CALL,
            "contact": SHARED_CONTACT,
            "direction": "incoming",
            "duration_seconds": 95,
        }
    ]
    messages = [
        {
            "timestamp": TS_MESSAGE,
            "contact": SHARED_CONTACT,
            "direction": "outgoing",
            "content": "Synthetic test message content.",
        }
    ]
    locations = [
        {
            "timestamp": TS_LOCATION,
            "latitude": SYNTHETIC_LATITUDE,
            "longitude": SYNTHETIC_LONGITUDE,
            "label": "Synthetic Point A",
            "accuracy": 12,
            "provider": "simulated_gps",
        }
    ]
    system_logs = [
        {
            "timestamp": TS_SYSTEM,
            "level": "INFO",
            "event": "boot_completed",
            "message": "Synthetic device finished booting.",
        }
    ]

    with zipfile.ZipFile(archive_path, "w") as archive:
        archive.writestr("device.json", json.dumps(device))
        archive.writestr("app_activity.json", json.dumps(app_activity))
        archive.writestr("calls.json", json.dumps(calls))
        archive.writestr("messages.json", json.dumps(messages))
        archive.writestr("locations.json", json.dumps(locations))
        archive.writestr("system_logs.json", json.dumps(system_logs))
        archive.writestr("notes.txt", "Synthetic, unsupported file. Should be skipped.")

    return archive_path


def build_malformed_evidence_zip(target_dir: Path) -> Path:
    """
    An archive that is a valid ZIP but whose evidence files are broken
    in three different ways - used to confirm the backend reports the
    problems instead of failing the whole request.
    """
    archive_path = target_dir / "malformed_evidence.zip"

    with zipfile.ZipFile(archive_path, "w") as archive:
        # Not valid JSON at all.
        archive.writestr("messages.json", "{ this is not valid json ")
        # Valid JSON, wrong structure for the parser.
        archive.writestr("calls.json", json.dumps({"unexpected": "shape"}))
        # Valid JSON and structure, but an out-of-range coordinate that
        # the location parser must reject.
        archive.writestr(
            "locations.json",
            json.dumps([{"timestamp": TS_LOCATION, "latitude": 999.0, "longitude": 0.0}]),
        )

    return archive_path


