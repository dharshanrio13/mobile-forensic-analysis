"""
Full end-to-end integration test for the Mobile Device Forensic
Analysis System backend.

This test does NOT assume a server is already running. It starts its own
fresh Uvicorn subprocess on a free localhost port, waits for /health to
respond, drives the real HTTP API, and shuts the process down again -
even if a test fails.

Nothing is mocked. Every assertion travels the whole pipeline:

    HTTP -> FastAPI route -> processing service -> ZIP extraction ->
    JSON loading -> existing parsers -> normalization -> application
    state -> timeline / correlation / report -> HTTP response

The evidence ZIP is generated by this file into a temporary directory,
so no sample archive in the repository is read or modified. The server
subprocess also gets its own UPLOAD_DIR and TEMP_DIR under that same
temporary directory, so running this test never writes into
backend/uploads or backend/temp.

Run it either way:

    pytest tests/test_full_integration.py -v
    python tests/test_full_integration.py

Environment overrides:
    TEST_HOST            (default 127.0.0.1)
    TEST_PORT            (default: an automatically chosen free port)
    TEST_STARTUP_TIMEOUT (default 45, seconds to wait for /health)
"""

import atexit
import json
import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time
import zipfile
from datetime import datetime
from pathlib import Path
from typing import Any, Dict, Optional

import requests

# backend/ - the directory Uvicorn must run from for `app.main:app` to
# import, and the parent of this tests/ package.
BACKEND_DIR = Path(__file__).resolve().parent.parent

STARTUP_TIMEOUT_SECONDS = float(os.getenv("TEST_STARTUP_TIMEOUT", "45"))
HEALTH_POLL_INTERVAL_SECONDS = 0.15
REQUEST_TIMEOUT_SECONDS = 30
SHUTDOWN_GRACE_SECONDS = 10

# Deterministic synthetic timestamps. Same instants every run.
_DAY = "2026-03-01"
TS_APP = f"{_DAY}T09:00:00+00:00"
TS_CALL = f"{_DAY}T09:05:00+00:00"
TS_MESSAGE = f"{_DAY}T09:07:00+00:00"
TS_LOCATION = f"{_DAY}T09:08:00+00:00"
TS_SYSTEM = f"{_DAY}T09:10:00+00:00"

# Shared synthetic identifier appearing on both a call and a message, so
# the existing shared_identifier rule has something deterministic to find.
SHARED_CONTACT = "+1-555-0100"

SYNTHETIC_LATITUDE = 12.6271
SYNTHETIC_LONGITUDE = 80.1927


# =====================================================================
# Server lifecycle
# =====================================================================


class BackendServer:
    """A Uvicorn subprocess running app.main:app, started for this test run."""

    def __init__(self) -> None:
        self.host = os.getenv("TEST_HOST", "127.0.0.1")
        self.port = int(os.getenv("TEST_PORT", "0")) or _find_free_port()
        self.base_url = f"http://{self.host}:{self.port}"
        self.process: Optional[subprocess.Popen] = None
        self._workspace: Optional[str] = None
        self._log_file = None
        self._log_path: Optional[Path] = None

    def start(self) -> None:
        """Launch the subprocess and block until /health answers."""
        # A plain mkdtemp, not TemporaryDirectory: the latter registers a
        # finalizer that calls rmtree at interpreter exit, and on Windows
        # that raises PermissionError if any handle on server.log is still
        # open - burying the real startup error under a second traceback.
        # Cleanup here is explicit, ordered, and never raises.
        self._workspace = tempfile.mkdtemp(prefix="forensic_test_")
        workspace = Path(self._workspace)
        (workspace / "uploads").mkdir()
        (workspace / "temp").mkdir()

        env = os.environ.copy()
        env["UPLOAD_DIR"] = str(workspace / "uploads")
        env["TEMP_DIR"] = str(workspace / "temp")
        env["PYTHONUNBUFFERED"] = "1"

        self._log_path = workspace / "server.log"
        # Opened write-only; read_log() opens its own separate handle, so
        # reading the log never interferes with the subprocess writing it.
        self._log_file = open(self._log_path, "w", encoding="utf-8")

        self.process = subprocess.Popen(
            [
                sys.executable,
                "-m",
                "uvicorn",
                "app.main:app",
                "--host",
                self.host,
                "--port",
                str(self.port),
                "--log-level",
                "warning",
            ],
            cwd=str(BACKEND_DIR),
            env=env,
            stdout=self._log_file,
            stderr=subprocess.STDOUT,
        )

        try:
            self._wait_for_health()
        except BaseException:
            # Startup failed (or was interrupted). Release the subprocess
            # and its log handle before propagating, so the caller sees the
            # real error rather than a cleanup error on top of it.
            self.stop()
            raise

    def _wait_for_health(self) -> None:
        """Poll /health until it answers, the process dies, or we time out."""
        deadline = time.monotonic() + STARTUP_TIMEOUT_SECONDS

        while time.monotonic() < deadline:
            if self.process is not None and self.process.poll() is not None:
                output = self.read_log()
                raise RuntimeError(
                    "Backend process exited during startup "
                    f"(exit code {self.process.returncode}).\n"
                    f"{_startup_hint(output)}\n"
                    f"--- server output ---\n{output}"
                )
            try:
                response = requests.get(f"{self.base_url}/health", timeout=2)
                if response.status_code == 200:
                    return
            except requests.RequestException:
                pass
            time.sleep(HEALTH_POLL_INTERVAL_SECONDS)

        raise RuntimeError(
            f"Backend did not become healthy within {STARTUP_TIMEOUT_SECONDS}s at "
            f"{self.base_url}/health.\n\n--- server output ---\n{self.read_log()}"
        )

    def read_log(self) -> str:
        """Whatever the subprocess has written so far, for failure reporting."""
        if self._log_path is None or not self._log_path.exists():
            return "(no server output captured)"
        try:
            return self._log_path.read_text(encoding="utf-8", errors="replace").strip() or "(empty)"
        except OSError as exc:
            return f"(could not read server log: {exc})"

    def stop(self) -> None:
        """
        Terminate the subprocess and clean up its workspace.

        Safe to call more than once, and never raises: a failure to tidy
        up must not mask whatever actually went wrong in the tests.
        Order matters on Windows - the child process has to be gone and
        the log handle closed before the directory can be removed.
        """
        if self.process is not None:
            if self.process.poll() is None:
                self.process.terminate()
                try:
                    self.process.wait(timeout=SHUTDOWN_GRACE_SECONDS)
                except subprocess.TimeoutExpired:
                    self.process.kill()
                    try:
                        self.process.wait(timeout=SHUTDOWN_GRACE_SECONDS)
                    except subprocess.TimeoutExpired:
                        pass
            self.process = None

        if self._log_file is not None:
            try:
                self._log_file.close()
            except OSError:
                pass
            self._log_file = None

        if self._workspace is not None:
            shutil.rmtree(self._workspace, ignore_errors=True)
            self._workspace = None


def _startup_hint(output: str) -> str:
    """
    Turn a known-shape startup failure into one actionable line.

    The import error below is by far the most common way this fails: an
    editor's "optimize imports" action rewrites `from app.api.routes.x`
    into `from api.routes.x`, which only resolves if backend/app is on
    sys.path - it isn't, because Uvicorn runs from backend/.
    """
    if "No module named 'api'" in output or "No module named 'core'" in output:
        return (
            "\nHINT: an import inside backend/app/ has lost its leading `app.`.\n"
            "      Every internal import must read `from app.<package>...`,\n"
            "      e.g. `from app.api.routes.cases import router`.\n"
            "      An IDE \"optimize imports\" action commonly strips it.\n"
        )
    if "No module named 'app'" in output:
        return (
            "\nHINT: Uvicorn could not find the `app` package. It must run with\n"
            "      backend/ as its working directory.\n"
        )
    if "No module named" in output:
        return (
            "\nHINT: a dependency is missing. Run:\n"
            "      pip install -r requirements.txt\n"
        )
    return ""


def _check_backend_imports() -> None:
    """
    Import the FastAPI app in a throwaway subprocess before starting the
    real server, so a broken import is reported as one clear message
    instead of a Uvicorn stack trace.
    """
    result = subprocess.run(
        [sys.executable, "-c", "import app.main"],
        cwd=str(BACKEND_DIR),
        capture_output=True,
        text=True,
    )
    if result.returncode != 0:
        output = (result.stderr or result.stdout).strip()
        raise RuntimeError(
            "backend/app/main.py could not be imported, so the server would "
            f"never start.\n{_startup_hint(output)}\n--- import error ---\n{output}"
        )


def _find_free_port() -> int:
    """Ask the OS for an unused localhost port."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as sock:
        sock.bind(("127.0.0.1", 0))
        return sock.getsockname()[1]


# One server per test session, started on first use and always stopped
# at process exit - so cleanup happens whether tests pass, fail, or
# error out. This works identically under pytest and the standalone
# runner at the bottom of this file, without needing pytest fixtures.
_server: Optional[BackendServer] = None


def base_url() -> str:
    """Start the backend if it isn't running yet, and return its base URL."""
    global _server
    if _server is None:
        _check_backend_imports()
        server = BackendServer()
        server.start()
        _server = server
        atexit.register(stop_server)
    return _server.base_url


def stop_server() -> None:
    global _server
    if _server is not None:
        _server.stop()
        _server = None


