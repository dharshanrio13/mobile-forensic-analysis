def _collect_tests():
    return [
        (name, obj)
        for name, obj in sorted(globals().items())
        if name.startswith("test_") and callable(obj)
    ]


def main() -> int:
    failures = []
    tests = _collect_tests()

    print(f"Running {len(tests)} integration tests against a fresh backend process.\n")

    try:
        url = base_url()
        print(f"Backend ready at {url}\n")

        for name, test in tests:
            try:
                test()
            except AssertionError as exc:
                print(f"[FAIL] {name}: {exc}")
                failures.append(name)
            except Exception as exc:  # noqa: BLE001 - report, don't abort the run
                print(f"[ERROR] {name}: {type(exc).__name__}: {exc}")
                failures.append(name)
            else:
                print(f"[PASS] {name}")
    except Exception as exc:  # noqa: BLE001 - startup failure
        print(f"\n[ERROR] Could not run tests: {exc}")
        return 1
    finally:
        stop_server()

    print()
    if failures:
        print(f"{len(failures)} of {len(tests)} tests FAILED: {', '.join(failures)}")
        return 1

    print(f"All {len(tests)} tests PASSED.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
