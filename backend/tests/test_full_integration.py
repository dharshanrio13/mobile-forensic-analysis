# Shared across the ordered test functions below.
_ctx: Dict[str, Any] = {}


def _url(path: str) -> str:
    return f"{base_url()}{path}"


def _create_case(name: str, description: str) -> str:
    response = requests.post(
        _url("/cases"),
        json={"name": name, "description": description},
        timeout=REQUEST_TIMEOUT_SECONDS,
    )
    assert response.status_code == 201, response.text
    return response.json()["id"]


def _upload(case_id: str, archive_path: Path) -> requests.Response:
    with open(archive_path, "rb") as handle:
        return requests.post(
            _url(f"/cases/{case_id}/evidence"),
            files={"file": (archive_path.name, handle, "application/zip")},
            timeout=REQUEST_TIMEOUT_SECONDS,
        )


def _assert_iso_timestamp(value: str) -> datetime:
    parsed = datetime.fromisoformat(str(value).replace("Z", "+00:00"))
    assert parsed.year == 2026, f"Unexpected timestamp: {value}"
    return parsed


