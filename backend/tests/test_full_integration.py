def test_07_upload_synthetic_evidence() -> None:
    with tempfile.TemporaryDirectory(prefix="forensic_evidence_") as tmp_dir:
        archive = build_synthetic_evidence_zip(Path(tmp_dir))
        response = _upload(_ctx["case_id"], archive)

    assert response.status_code == 201, response.text
    payload = response.json()

    assert payload["success"] is True
    assert payload["case_id"] == _ctx["case_id"]
    assert payload["evidence_id"]
    assert payload["original_filename"] == "synthetic_evidence.zip"
    assert payload["processing_status"] == "processed", payload

    # Integrity: a 64-character lowercase hex SHA-256 digest.
    digest = payload["sha256"]
    assert isinstance(digest, str) and len(digest) == 64, digest
    assert all(char in "0123456789abcdef" for char in digest), digest

    extracted = payload["extracted_files"]
    for expected_file in (
        "device.json",
        "app_activity.json",
        "calls.json",
        "messages.json",
        "locations.json",
        "system_logs.json",
    ):
        assert expected_file in extracted, f"{expected_file} not extracted: {extracted}"

    # The unsupported file must have been skipped, not extracted.
    assert "notes.txt" not in extracted
    assert any("notes.txt" in entry.get("entry", "") for entry in payload["skipped_files"]), payload[
        "skipped_files"
    ]

    # 2 app + 1 call + 1 message + 1 location + 1 system = 6 events.
    assert payload["processed_event_count"] == 6, payload
    assert payload["normalization_error_count"] == 0, payload
    assert payload["device_info"]["device_id"] == "SYNTHETIC-DEVICE-0001"

    # No server filesystem paths leak into the response.
    assert "saved_path" not in payload
    assert "file_path" not in json.dumps(payload["evidence_items"])

    _ctx["evidence_id"] = payload["evidence_id"]


