def test_12_analysis() -> None:
    response = requests.get(
        _url(f"/cases/{_ctx['case_id']}/analysis"), timeout=REQUEST_TIMEOUT_SECONDS
    )
    assert response.status_code == 200, response.text

    payload = response.json()
    assert payload["case_id"] == _ctx["case_id"]
    assert payload["total_events"] == 6, payload
    assert isinstance(payload["correlations"], list)
    assert payload["total_correlations"] == len(payload["correlations"])
    assert payload["total_correlations"] > 0, "Synthetic data should produce correlations"

    rules = {correlation["rule"] for correlation in payload["correlations"]}
    # The synthetic data is designed so all three deterministic rules fire:
    # every event is within 15 minutes of the others, a call and a message
    # share one contact identifier, and a location sits beside other activity.
    for expected_rule in ("time_window", "shared_identifier", "location_proximity"):
        assert expected_rule in rules, f"Rule '{expected_rule}' did not appear: {rules}"

    for correlation in payload["correlations"]:
        for key in ("correlation_id", "related_event_ids", "reason", "rule", "context"):
            assert key in correlation, f"Missing '{key}' in correlation: {correlation}"
        assert len(correlation["related_event_ids"]) >= 2

    shared = [c for c in payload["correlations"] if c["rule"] == "shared_identifier"]
    assert any(c["context"].get("identifier") == SHARED_CONTACT for c in shared), shared

    # Forensic wording: no claims of guilt or criminality anywhere.
    text = json.dumps(payload).lower()
    for forbidden in ("guilty", "criminal", "proves", "committed the crime"):
        assert forbidden not in text, f"Analysis contains unsupported wording: {forbidden}"


